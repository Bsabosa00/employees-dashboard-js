function avg(arr) {
    return arr.reduce((a,b)=>a+b,0)/arr.length;
}
function totalSalary(){
    let total = 0;
    employees.forEach(emp => {
        emp.salary.forEach(s => total += s);
    });
    document.getElementById("totalSalary").innerText=
    "Total company Salary: " + total;
}

function render(list){
    let container = document.getElementById("employeesContainer");
    container.innerHTML ="";

    list.forEach(emp => {
        let card = document.createElement("div");
        card.classList = "card";

        card.innerHTML = 
        `<h2>${emp.name}</h2>
        <p>${emp.jobTitle}</p>
        <button onclick="toggleDetailes(this)">Show Details</button>
        
        <div class="details">
            <p>Age : ${emp.age}</p>
            <p>Manager : ${emp.isManager ? "Yes" : "No"}</p>
            <p>City : ${emp.address.city}</p>
            <p>Skills : ${emp.skills.join(", ")}</p>
            <p>Salary : ${emp.salary.join(", ")}</p>
            <p>Avg Salary : ${avg(emp.salary).toFixed(2)}</p>
        </div>`
        ;
        container.appendChild(card);
    });
}
function toggleDetailes(btn){
    let card = btn.parentElement;
    card.classList.toggle("active");

    if(card.classList.contains("active")){
        btn.innerText = "Hide Details";
    }else{
        btn.innerText = "Show Details";
    }
}
document.getElementById("search").addEventListener("input", function(){
    let value = this.value.toLowerCase();
    let filtered = employees.filter(e => 
        e.name.toLowerCase().includes(value)
    );
    render(filtered);
});
document.getElementById("filter").addEventListener("change", function(){
    if(this.value === "manager") {
        render(employees.filter(e => e.isManager));
    }else{
        render(employees)
    }
});
